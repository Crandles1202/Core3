function FbArmoryDroid:start()
	for _, spawn in ipairs(self.spawns) do
		if isZoneEnabled(spawn.planet) then
			spawnMobile(spawn.planet, "fb_armory_droid", 0,
				spawn.x, spawn.z, spawn.y, spawn.dir, spawn.cellID or 0)
		end
	end
	printf("FbArmoryDroid: spawned\n")
end

-- ============================================================================
-- Stateless per-category callbacks. Same pattern as FB-44.
-- ============================================================================
function FbArmoryDroid:_purchaseFromCategory(pPlayer, eventIndex, args, catIdx)
	if pPlayer == nil then return end
	if eventIndex == 1 then return end

	local creature = CreatureObject(pPlayer)
	if catIdx < 1 or catIdx > #FbArmoryDroid.weaponCategories then return end

	local idx = tonumber(args)
	if idx == nil then return end

	-- args=0 -> "Buy one of each (testing)", args>=1 -> individual weapon
	if idx == 0 then
		FbArmoryDroid:_purchaseOneOfEach(pPlayer, catIdx)
		return
	end

	local cat = FbArmoryDroid.weaponCategories[catIdx]
	if idx < 1 or idx > #cat.items then return end

	local item = cat.items[idx]

	if creature:getCashCredits() < item.price then
		creature:sendSystemMessage("Not enough credits for " .. item.name .. ". Need " .. item.price .. " cr.")
		return
	end

	local pInventory = creature:getSlottedObject("inventory")
	if pInventory == nil then
		creature:sendSystemMessage("Cannot access inventory.")
		return
	end

	if SceneObject(pInventory):isContainerFullRecursive() then
		creature:sendSystemMessage("Inventory full.")
		return
	end

	local pItem = giveItem(pInventory, item.template, -1)
	if pItem == nil then
		creature:sendSystemMessage("Transaction failed (template may not be spawnable): " .. item.template)
		return
	end

	creature:subtractCashCredits(item.price)
	creature:sendSystemMessage("Purchased " .. item.name .. " (" .. cat.name .. ") for " .. item.price .. " credits.")
end

-- ============================================================================
-- "Buy one of each" — testing helper that quickly verifies which weapon
-- templates in a category are spawnable. Charges per-success same as armor
-- bulk-buy. Useful for finding broken/abstract templates.
-- ============================================================================
function FbArmoryDroid:_purchaseOneOfEach(pPlayer, catIdx)
	if pPlayer == nil then return end
	local creature = CreatureObject(pPlayer)
	local cat = FbArmoryDroid.weaponCategories[catIdx]

	local total = 0
	for i = 1, #cat.items do total = total + cat.items[i].price end

	if creature:getCashCredits() < total then
		creature:sendSystemMessage("Not enough credits for one of each in " .. cat.name .. ". Need " .. total .. " cr.")
		return
	end

	local pInventory = creature:getSlottedObject("inventory")
	if pInventory == nil then
		creature:sendSystemMessage("Cannot access inventory.")
		return
	end
	if SceneObject(pInventory):isContainerFullRecursive() then
		creature:sendSystemMessage("Inventory full.")
		return
	end

	local givenCount = 0
	local totalSpent = 0
	local failed = {}

	for i = 1, #cat.items do
		local item = cat.items[i]
		if SceneObject(pInventory):isContainerFullRecursive() then
			table.insert(failed, item.name .. " (inventory full)")
		else
			local pItem = giveItem(pInventory, item.template, -1)
			if pItem ~= nil then
				givenCount = givenCount + 1
				totalSpent = totalSpent + item.price
			else
				table.insert(failed, item.name)
			end
		end
	end

	if totalSpent > 0 then creature:subtractCashCredits(totalSpent) end

	if givenCount == #cat.items then
		creature:sendSystemMessage("Got one of each " .. cat.name .. ": " .. givenCount .. " weapons for " .. totalSpent .. " credits.")
	elseif givenCount > 0 then
		creature:sendSystemMessage("Partial " .. cat.name .. ": " .. givenCount .. " of " .. #cat.items .. " weapons for " .. totalSpent .. " cr. Failed: " .. table.concat(failed, ", "))
	else
		creature:sendSystemMessage("No " .. cat.name .. " weapons delivered.")
	end
end

-- Generate per-category callbacks at file load time. Each closes over its
-- own catIdx so the SUI manager can dispatch by callback name.
for i = 1, #FbArmoryDroid.weaponCategories do
	local catIdx = i
	FbArmoryDroid["onWeaponPickedCat" .. catIdx] = function(self, pPlayer, pSui, eventIndex, args)
		FbArmoryDroid:_purchaseFromCategory(pPlayer, eventIndex, args, catIdx)
	end
end

-- ============================================================================
-- SUI step 1: category picker
-- ============================================================================
function FbArmoryDroid:showWeaponList(pPlayer, pNpc)
	if pPlayer == nil then return end
	local pSui = SuiListBox.new("FbArmoryDroid", "onCategoryPicked")
	pSui.setTitle("FB-72 — Weapons Catalogue")
	pSui.setPrompt("Select a weapon type to browse available weapons:")
	for i = 1, #FbArmoryDroid.weaponCategories do
		local cat = FbArmoryDroid.weaponCategories[i]
		pSui.add(cat.name .. "  (" .. #cat.items .. " weapons)", "")
	end
	pSui.sendTo(pPlayer)
end

-- ============================================================================
-- SUI step 2: category picked, open weapon list for that category
-- ============================================================================
function FbArmoryDroid:onCategoryPicked(pPlayer, pSui, eventIndex, args)
	if pPlayer == nil then return end
	if eventIndex == 1 then return end
	local catIdx = tonumber(args)
	if catIdx == nil then return end
	catIdx = catIdx + 1
	if catIdx < 1 or catIdx > #FbArmoryDroid.weaponCategories then return end

	local cat = FbArmoryDroid.weaponCategories[catIdx]
	local pInner = SuiListBox.new("FbArmoryDroid", "onWeaponPickedCat" .. catIdx)
	pInner.setTitle(cat.name)
	pInner.setPrompt("Pick a weapon to purchase, or buy one of each (testing):")

	-- "Buy one of each" entry at index 0
	local total = 0
	for i = 1, #cat.items do total = total + cat.items[i].price end
	pInner.add("[" .. total .. " cr]  *** Buy one of each (" .. #cat.items .. " weapons, testing) ***", "")

	for i = 1, #cat.items do
		local it = cat.items[i]
		pInner.add("[" .. it.price .. " cr] " .. it.name, "")
	end
	pInner.sendTo(pPlayer)
end
