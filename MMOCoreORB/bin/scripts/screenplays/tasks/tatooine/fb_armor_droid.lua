-- ============================================================================
-- SUI step 1: show category picker
-- ============================================================================
function FbArmorDroid:showCategoryList(pPlayer, pNpc)
	if pPlayer == nil then return end
	local pSui = SuiListBox.new("FbArmorDroid", "onCategoryPicked")
	pSui.setTitle("FB-44 — Armor Catalogue")
	pSui.setPrompt("Select an armor type to view available pieces:")
	for i = 1, #self.armorCategories do
		local cat = self.armorCategories[i]
		pSui.add(cat.name .. "  (" .. #cat.items .. " pieces)", "")
	end
	pSui.sendTo(pPlayer)
end

-- ============================================================================
-- Stateless approach — generate one SUI callback per category at load time.
-- Each callback name encodes its catIdx ("onItemPickedCat1", "onItemPickedCat2",
-- etc.), so no shared state is needed between the two SUI callbacks.
-- Earlier attempts to use FbArmorDroid.pendingCategory failed because the two
-- SUI callbacks apparently run in contexts where the table state isn't shared.
-- ============================================================================
function FbArmorDroid:_purchaseFromCategory(pPlayer, eventIndex, args, catIdx)
	if pPlayer == nil then return end
	if eventIndex == 1 then return end  -- Cancel

	local creature = CreatureObject(pPlayer)

	if catIdx < 1 or catIdx > #FbArmorDroid.armorCategories then
		creature:sendSystemMessage("FB-44 error: invalid category " .. tostring(catIdx))
		return
	end

	local idx = tonumber(args)
	if idx == nil then return end

	-- SUI option layout:
	--   args=0 -> "Buy entire set"
	--   args=1..N -> individual piece (items[args])
	if idx == 0 then
		FbArmorDroid:_purchaseEntireSet(pPlayer, catIdx)
		return
	end

	local cat = FbArmorDroid.armorCategories[catIdx]
	if idx < 1 or idx > #cat.items then return end

	local item = cat.items[idx]

	if creature:getCashCredits() < item.price then
		creature:sendSystemMessage("Not enough credits for " .. item.name .. ". Need " .. item.price .. " cr.")
		return
	end

	local pInventory = creature:getSlottedObject("inventory")
	if pInventory == nil then
		creature:sendSystemMessage("Cannot access inventory.")
		return
	end

	if SceneObject(pInventory):isContainerFullRecursive() then
		creature:sendSystemMessage("Inventory full.")
		return
	end

	local pItem = giveItem(pInventory, item.template, -1)
	if pItem == nil then
		creature:sendSystemMessage("Transaction failed (template may not be spawnable): " .. item.template)
		return
	end

	creature:subtractCashCredits(item.price)
	creature:sendSystemMessage("Purchased " .. item.name .. " (" .. cat.name .. ") for " .. item.price .. " credits.")
end

-- ============================================================================
-- Bulk purchase: buy every piece in the category in one transaction.
-- Pre-checks total credits and inventory space. If individual giveItem calls
-- fail (e.g. one template is abstract), charges only for successful pieces
-- and reports which pieces couldn't be delivered.
-- ============================================================================
function FbArmorDroid:_purchaseEntireSet(pPlayer, catIdx)
	if pPlayer == nil then return end
	local creature = CreatureObject(pPlayer)
	local cat = FbArmorDroid.armorCategories[catIdx]

	-- Sum total price
	local total = 0
	for i = 1, #cat.items do
		total = total + cat.items[i].price
	end

	-- Credit check
	if creature:getCashCredits() < total then
		creature:sendSystemMessage("Not enough credits for the full " .. cat.name .. " set. Need " .. total .. " cr.")
		return
	end

	-- Inventory access + initial space check
	local pInventory = creature:getSlottedObject("inventory")
	if pInventory == nil then
		creature:sendSystemMessage("Cannot access inventory.")
		return
	end
	if SceneObject(pInventory):isContainerFullRecursive() then
		creature:sendSystemMessage("Your inventory is full. Free up some space and try again.")
		return
	end

	-- Loop and deliver. Track successes vs failures for honest reporting.
	local givenCount = 0
	local totalSpent = 0
	local failed = {}

	for i = 1, #cat.items do
		local item = cat.items[i]

		-- Re-check inventory before each give in case we filled it mid-loop
		if SceneObject(pInventory):isContainerFullRecursive() then
			table.insert(failed, item.name .. " (inventory full)")
		else
			local pItem = giveItem(pInventory, item.template, -1)
			if pItem ~= nil then
				givenCount = givenCount + 1
				totalSpent = totalSpent + item.price
			else
				table.insert(failed, item.name)
			end
		end
	end

	-- Charge only for items actually delivered.
	if totalSpent > 0 then
		creature:subtractCashCredits(totalSpent)
	end

	-- Report
	if givenCount == #cat.items then
		creature:sendSystemMessage("Purchased the full " .. cat.name .. " set: " .. givenCount .. " pieces for " .. totalSpent .. " credits.")
	elseif givenCount > 0 then
		creature:sendSystemMessage("Partial " .. cat.name .. " set: " .. givenCount .. " of " .. #cat.items .. " pieces for " .. totalSpent .. " credits. Failed: " .. table.concat(failed, ", "))
	else
		creature:sendSystemMessage("Could not deliver any " .. cat.name .. " pieces. All templates failed or inventory full.")
	end
end

-- Generate per-category callbacks at file load. Each closes over its own
-- catIdx, so the SUI manager just needs to invoke "onItemPickedCat<N>" and
-- the right purchase logic runs with the right category baked in.
for i = 1, #FbArmorDroid.armorCategories do
	local catIdx = i  -- close over local copy
	FbArmorDroid["onItemPickedCat" .. catIdx] = function(self, pPlayer, pSui, eventIndex, args)
		FbArmorDroid:_purchaseFromCategory(pPlayer, eventIndex, args, catIdx)
	end
end

-- ============================================================================
-- SUI step 2: category picked, show that category's items
-- ============================================================================
function FbArmorDroid:onCategoryPicked(pPlayer, pSui, eventIndex, args)
	if pPlayer == nil then return end
	if eventIndex == 1 then return end  -- Cancel
	local catIdx = tonumber(args)
	if catIdx == nil then return end
	catIdx = catIdx + 1
	if catIdx < 1 or catIdx > #FbArmorDroid.armorCategories then return end

	-- Open the second SUI with a category-specific callback name.
	-- The catIdx is baked into the callback name itself — no state passing.
	local cat = FbArmorDroid.armorCategories[catIdx]
	local pInner = SuiListBox.new("FbArmorDroid", "onItemPickedCat" .. catIdx)
	pInner.setTitle(cat.name)
	pInner.setPrompt("Pick a single piece, or buy the entire set:")

	-- Calculate set total and add the "Buy entire set" option as index 0
	-- (always first). Individual pieces follow at indices 1..N matching
	-- their position in the items table.
	local setTotal = 0
	for i = 1, #cat.items do
		setTotal = setTotal + cat.items[i].price
	end
	pInner.add("[" .. setTotal .. " cr]  *** Buy entire set (" .. #cat.items .. " pieces) ***", "")

	for i = 1, #cat.items do
		local it = cat.items[i]
		pInner.add("[" .. it.price .. " cr] " .. it.name, "")
	end
	pInner.sendTo(pPlayer)
end
