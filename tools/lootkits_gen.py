#!/usr/bin/env python3
"""The loot-kit data generator (Phase 2.4). Writes, from the quality ladder in docs/Loot-Kits-Design.md:
  tre-src/string/en/fb_kits.stf.txt                                      names and descriptions
  MMOCoreORB/bin/scripts/custom_scripts/object/tangible/fb_kits/fb_kits.lua  kit and part object templates
  MMOCoreORB/bin/scripts/custom_scripts/loot/items/fb_kits.lua           loot items (parts, kits, rewards) and loot groups
Run from the repo root after changing a tier, a set or a weapon line; never edit the generated files by hand.
The six weapon lines' damage and speed are read from their stock templates."""
import re, os
O="MMOCoreORB/bin/scripts/object"
def weapon(path):
    s=open(f"{O}/weapon/{path}.lua").read()
    g=lambda k: float(re.search(r"\b%s = ([0-9.]+)" % k, s).group(1))
    return dict(min=g("minDamage"), max=g("maxDamage"), speed=g("attackSpeed"))
KIT_LOOK="object/tangible/loot/simple_kit/shared_datadisk_repair_kit.iff"
# damage-type bits (SharedWeaponObjectTemplate) and each type's loot key
TYPES=[("kinetic",1),("energy",2),("blast",4),("stun",8),("lightsaber",16),("heat",32),("cold",64),("acid",128),("electricity",256)]
TYPEKEY={"kinetic":"kineticeffectiveness","energy":"energyeffectiveness","blast":"blasteffectiveness","stun":"stuneffectiveness","lightsaber":"lightsabereffectiveness","heat":"heateffectiveness","cold":"coldeffectiveness","acid":"acideffectiveness","electricity":"electricaleffectiveness"}
def vulnerability(tpl_path):
    """the stock piece's vulnerability bitmask (its Lua: vulnerability = KINETIC + BLAST + …)"""
    s=open(f"{O}/tangible/wearables/armor/{tpl_path}.lua").read()
    m=re.search(r"vulnerability\s*=\s*([A-Z_ +]+)", s)
    bits=0
    if m:
        for name in m.group(1).replace(" ","").split("+"):
            for t,b in TYPES:
                if t.upper()==name: bits|=b
    return bits
ARMOR_PARTS=[("plating","Armor Plating","object/tangible/component/armor/shared_armor_segment.iff"),
             ("mesh","Armor Mesh","object/tangible/component/armor/shared_armor_layer.iff"),
             ("fastener","Armor Fasteners","object/tangible/component/armor/shared_armor_layer_kinetic.iff"),
             ("lining","Armor Lining","object/tangible/component/armor/shared_armor_layer_environmental.iff"),
             ("trim","Armor Trim","object/tangible/component/armor/shared_armor_layer_energy.iff")]
WEAPON_PARTS=[("mechanism","Weapon Mechanism","object/tangible/component/weapon/shared_projectile_feed_mechanism.iff"),
              ("cell","Power Cell","object/tangible/component/weapon/shared_blaster_power_handler.iff"),
              ("barrel","Barrel Assembly","object/tangible/component/weapon/shared_blaster_barrel_wp_muzzle_lg_s01.iff"),
              ("core","Reinforcement Core","object/tangible/component/weapon/shared_reinforcement_core.iff"),
              ("sight","Sight","object/tangible/component/weapon/shared_scope_weapon.iff")]
TIER_PARTS={1:3,2:4,3:5}
ROMAN={1:"I",2:"II",3:"III"}
PIECES_STD=[("chest_plate","Chest Plate"),("helmet","Helmet"),("boots","Boots"),("gloves","Gloves"),("leggings","Leggings"),("bicep_l","Left Bicep"),("bicep_r","Right Bicep"),("bracer_l","Left Bracer"),("bracer_r","Right Bracer")]
SETS={1:[("padded","Padded",lambda p:f"padded/armor_padded_s01_{p}",PIECES_STD+[("belt","Belt")],(1,1,1),None),
         ("bone","Bone",lambda p:f"bone/armor_bone_s01_{p}",PIECES_STD,(56,22,4),None)],
      2:[("composite","Composite",lambda p:f"composite/armor_composite_{p}",PIECES_STD,(300,120,85),"kineticeffectiveness"),
         ("ubese","Ubese",lambda p:f"ubese/armor_ubese_{p}",[("jacket","Jacket"),("pants","Pants"),("shirt","Shirt"),("boots","Boots"),("gloves","Gloves"),("helmet","Helmet"),("bracer_l","Left Bracer"),("bracer_r","Right Bracer"),("bandolier","Bandolier")],(1,1,1),"energyeffectiveness"),
         ("chitin","Chitin",lambda p:f"chitin/armor_chitin_s01_{p}",PIECES_STD,(100,40,20),"blasteffectiveness")],
      3:[("composite_adv","Veteran Composite",lambda p:f"composite/armor_composite_{p}",PIECES_STD,(300,120,85),"kineticeffectiveness")]}
ARMOR_TIER={1:dict(lo=28,hi=33,integ=15000,special=0),2:dict(lo=42,hi=48,integ=25000,special=10),3:dict(lo=52,hi=58,integ=35000,special=15)}
WEAPONS=[("dl44","DL44 Pistol","ranged/pistol/pistol_dl44"),("dh17","DH17 Carbine","ranged/carbine/carbine_dh17"),("e11","E11 Rifle","ranged/rifle/rifle_e11"),
         ("sword","Sword","melee/sword/sword_01"),("katana","Katana","melee/2h_sword/2h_sword_katana"),("staff","Metal Staff","melee/polearm/lance_staff_metal")]
WEAPON_TIER={1:dict(f=0.9,sp=0.95,integ=15000),2:dict(f=1.2,sp=0.90,integ=25000),3:dict(f=1.4,sp=0.85,integ=35000)}
strings=["# Final Boss loot kits (Phase 2.4): kits, parts, lines. Generated by tools/lootkits_gen.py; edit the generator, not this file.", ""]
templ=["-- fb_kits.lua — every loot-kit object and part (Phase 2.4), generated by tools/lootkits_gen.py. A kit is the stock Pre-CU",
       "-- loot-kit object (LOOTKIT) with a stock kit's look, the tier's parts as its components and a *loot item* as its reward",
       "-- (collectibleLootReward: our engine addition, so the piece gets the tier's rolled stats). Parts are plain tangibles.", ""]
items=["-- fb_kits.lua (loot) — the loot items and groups of the loot kits (Phase 2.4), generated by tools/lootkits_gen.py: parts and",
       "-- kits as drops, and the finished pieces as the kits' rewards with the quality ladder's stats (docs/Loot-Kits-Design.md).", ""]
def part_path(cls,kind,t): return f"object/tangible/fb_kits/part_{cls}_{kind}_{t}.iff"
def kit_path(kid): return f"object/tangible/fb_kits/kit_{kid}.iff"
def luaname(path): return path.replace("/","_").replace(".iff","")
groups={}
for cls,parts in (("armor",ARMOR_PARTS),("weapon",WEAPON_PARTS)):
    for t in (1,2,3):
        g=[]
        for kind,label,look in parts:
            p=part_path(cls,kind,t); n=luaname(p)
            strings.append(f"part_{cls}_{kind}_{t} = {label} ({ROMAN[t]})")
            strings.append(f"part_{cls}_{kind}_{t}_d = A salvaged {label.lower()}, tier {ROMAN[t]}. Drag it into a matching {cls} kit.")
            templ.append(f'{n} = SharedTangibleObjectTemplate:new {{ clientTemplateFileName = "{look}", objectName = "@fb_kits:part_{cls}_{kind}_{t}", detailedDescription = "@fb_kits:part_{cls}_{kind}_{t}_d", gameObjectType = 8249 }}')
            templ.append(f'ObjectTemplates:addTemplate({n}, "{p}")')
            items.append(f'fb_part_{cls}_{kind}_{t} = {{ minimumLevel = 0, maximumLevel = -1, customObjectName = "", directObjectTemplate = "{p}", craftingValues = {{}}, customizationStringNames = {{}}, customizationValues = {{}} }}')
            items.append(f'addLootItemTemplate("fb_part_{cls}_{kind}_{t}", fb_part_{cls}_{kind}_{t})')
            g.append(f"fb_part_{cls}_{kind}_{t}")
        groups[f"fb_kit_parts_{cls}_{t}"]=g
def kit(kid, label, cls, t, reward_item):
    parts=(ARMOR_PARTS if cls=="armor" else WEAPON_PARTS)[:TIER_PARTS[t]]
    comps=", ".join(f'"{part_path(cls,k,t)}"' for k,_,_ in parts)
    n=luaname(kit_path(kid))
    strings.append(f"kit_{kid} = {label} Kit ({ROMAN[t]})")
    strings.append(f"kit_{kid}_d = Needs {len(parts)} tier-{ROMAN[t]} {cls} parts: " + ", ".join(l.lower() for _,l,_ in parts) + ". Drag them in; the last one finishes the piece.")
    templ.append(f'{n} = object_tangible_loot_simple_kit_shared_datadisk_repair_kit:new {{ templateType = LOOTKIT, gameObjectType = 8233, clientTemplateFileName = "{KIT_LOOK}", objectName = "@fb_kits:kit_{kid}", detailedDescription = "@fb_kits:kit_{kid}_d", collectibleComponents = {{ {comps} }}, collectibleReward = {{}}, collectibleLootReward = {{ "{reward_item}" }}, deleteComponents = 1, attributes = {{}} }}')
    templ.append(f'ObjectTemplates:addTemplate({n}, "{kit_path(kid)}")')
    items.append(f'fb_kit_{kid} = {{ minimumLevel = 0, maximumLevel = -1, customObjectName = "", directObjectTemplate = "{kit_path(kid)}", craftingValues = {{}}, customizationStringNames = {{}}, customizationValues = {{}} }}')
    items.append(f'addLootItemTemplate("fb_kit_{kid}", fb_kit_{kid})')
for t,sets in SETS.items():
    a=ARMOR_TIER[t]
    for sid,slabel,tpl,pieces,(eh,ea,em),special in sets:
        g=[]
        for pid,plabel in pieces:
            kid=f"{sid}_{pid}_{t}"; reward=f"fb_reward_{kid}"
            # Every type the stock piece protects is spelled out as a special with its own delta (0, or the set's bonus), and
            # armor_special_type names exactly those bits: left absent, ArmorObject reads the not-found sentinel as the bitmask
            # and one stray type per set shows a garbage value (found 2026-10-26). The stock vulnerabilities stay (a vulnerable
            # type shows nothing); the shown value of a protected type = armor_special_effectiveness roll + its delta.
            vuln=vulnerability(tpl(pid))
            protected=[(typ,b) for typ,b in TYPES if not (vuln & b) and typ!="lightsaber"]
            mask=sum(b for _,b in protected)
            cv=[f'{{"armor_effectiveness", {a["lo"]}, {a["hi"]}, 0}}', f'{{"armor_special_effectiveness", {a["lo"]}, {a["hi"]}, 0}}',
                f'{{"armor_special_type", {mask}, {mask}, 0}}', f'{{"armor_integrity", {a["integ"]}, {a["integ"]}, 0}}',
                f'{{"armor_health_encumbrance", {eh}, {eh}, 0}}', f'{{"armor_action_encumbrance", {ea}, {ea}, 0}}', f'{{"armor_mind_encumbrance", {em}, {em}, 0}}']
            for typ,b in protected:
                delta = a["special"] if (special == TYPEKEY[typ] and a["special"]) else 0
                cv.append(f'{{"{TYPEKEY[typ]}", {delta}, {delta}, 0}}')
            items.append(f'{reward} = {{ minimumLevel = 0, maximumLevel = -1, customObjectName = "", directObjectTemplate = "object/tangible/wearables/armor/{tpl(pid)}.iff", craftingValues = {{ {", ".join(cv)} }}, customizationStringNames = {{}}, customizationValues = {{}} }}')
            items.append(f'addLootItemTemplate("{reward}", {reward})')
            kit(kid, f"{slabel} {plabel}", "armor", t, reward)
            g.append(f"fb_kit_{kid}")
        groups[f"fb_kits_{sid}_{t}"]=g
for t in (1,2,3):
    w=WEAPON_TIER[t]; g=[]
    for wid,wlabel,wpath in WEAPONS:
        v=weapon(wpath); kid=f"{wid}_{t}"; reward=f"fb_reward_{kid}"
        mn=int(round(v["min"]*w["f"])); mx=int(round(v["max"]*w["f"])); sp=round(v["speed"]*w["sp"],2)
        cv=[f'{{"mindamage", {mn}, {mn}, 0}}', f'{{"maxdamage", {mx}, {mx}, 0}}', f'{{"attackspeed", {sp}, {sp}, 2}}', f'{{"hitpoints", {w["integ"]}, {w["integ"]}, 0}}']
        items.append(f'{reward} = {{ minimumLevel = 0, maximumLevel = -1, customObjectName = "", directObjectTemplate = "object/weapon/{wpath}.iff", craftingValues = {{ {", ".join(cv)} }}, customizationStringNames = {{}}, customizationValues = {{}} }}')
        items.append(f'addLootItemTemplate("{reward}", {reward})')
        kit(kid, wlabel, "weapon", t, reward)
        g.append(f"fb_kit_{kid}")
    groups[f"fb_kits_weapon_{t}"]=g
for t in (1,2,3):
    groups[f"fb_kits_{t}"]=[k for name,ks in groups.items() if name.startswith("fb_kits_") and name.endswith(f"_{t}") and name!=f"fb_kits_{t}" for k in ks]
items.append("")
for name,ks in groups.items():
    # the unit test (LuaLootGroupsTest) wants the weights of a group to sum to exactly 10 000 000: the last entry takes the remainder
    wgt=10000000//len(ks); last=10000000-wgt*(len(ks)-1)
    items.append(f"{name} = {{ description = \"\", minimumLevel = 0, maximumLevel = 0, lootItems = {{ " + ", ".join(f'{{itemTemplate = "{k}", weight = {wgt if i < len(ks)-1 else last}}}' for i,k in enumerate(ks)) + " } }")
    items.append(f'addLootGroupTemplate("{name}", {name})')
os.makedirs("MMOCoreORB/bin/scripts/custom_scripts/object/tangible/fb_kits", exist_ok=True)
open("tre-src/string/en/fb_kits.stf.txt","w").write("\n".join(strings)+"\n")
open("MMOCoreORB/bin/scripts/custom_scripts/object/tangible/fb_kits/fb_kits.lua","w").write("\n".join(templ)+"\n")
open("MMOCoreORB/bin/scripts/custom_scripts/loot/items/fb_kits.lua","w").write("\n".join(items)+"\n")
print("kits", sum(1 for l in templ if "templateType = LOOTKIT" in l), "parts", sum(1 for l in templ if "SharedTangibleObjectTemplate:new" in l), "groups", len(groups))
