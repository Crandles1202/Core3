#!/usr/bin/env python3
"""foods_gen.py — the food vendor's shelves (Final Boss 2.16), generated from the game's own data.

Every crafted dish, dessert and drink (object/tangible/food/crafted/{dish,dessert,drink}_*) becomes a row with a master
chef's numbers read off the template's experimentation bands (nutrition and duration at their best, uses at the most,
filling at the least); the cantina (bartender) drinks come as they are. Spice — the smugglers' trade — is left out.
Names come from the game's food_name table out of the archives (the key is the file stem without its kind prefix).
Edit this generator, not the Lua it writes.

  tools/foods_gen.py            # writes MMOCoreORB/bin/scripts/screenplays/tasks/tatooine/fb_food_vendor_catalogue.lua
  tools/foods_gen.py --list
"""
import glob, importlib.machinery, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "MMOCoreORB", "bin", "scripts")
OUT = os.path.join(ROOT, "screenplays", "tasks", "tatooine", "fb_food_vendor_catalogue.lua")
CG = importlib.machinery.SourceFileLoader("components_gen", os.path.join(HERE, "components_gen.py")).load_module()
KINDS = [("dish", "Dishes", 500), ("dessert", "Desserts", 400), ("drink", "Drinks", 300)]
CANTINA_PRICE = 150

def num(body, key, default=None):
    m = re.search(r"\b%s\s*=\s*(-?\d+(?:\.\d+)?)" % key, body)
    return float(m.group(1)) if m else default

def rows():
    out = {}
    for kind, shelf, price in KINDS:
        for f in sorted(glob.glob(os.path.join(ROOT, "object", "tangible", "food", "crafted", kind + "_*.lua"))):
            body = open(f).read()
            if not re.search(r"addTemplate\(", body):
                continue
            stem = os.path.basename(f)[:-4]
            path = "object/tangible/food/crafted/%s.iff" % stem
            key = stem[len(kind) + 1:]
            name = CG.stf_table("food_name").get(key) or CG.human(key)
            nmin, nmax = num(body, "nutritionMin", 0), num(body, "nutritionMax", 0)
            fmin, fmax = num(body, "flavorMin", 0), num(body, "flavorMax", 0)
            qmin, qmax = num(body, "quantityMin", 1), num(body, "quantityMax", 1)
            filmin, filmax = num(body, "fillingMin", 10), num(body, "fillingMax", 10)
            species = (re.search(r'speciesRestriction\s*=\s*"([^"]*)"', body) or [None, ""])[1]
            if species == "pets":
                continue
            out.setdefault(shelf, []).append(dict(name=name.strip(), template=path, price=price,
                nutrition=int(max(nmin, nmax)), duration=int(max(fmin, fmax)), quantity=int(max(qmin, qmax)), filling=int(min(filmin, filmax)),
                species=species))
    for f in sorted(glob.glob(os.path.join(ROOT, "object", "tangible", "food", "bartender_drinks", "*.lua"))):
        body = open(f).read()
        if not re.search(r"addTemplate\(", body):
            continue
        stem = os.path.basename(f)[:-4]
        name = CG.stf_table("food_name").get(stem) or CG.human(stem)
        out.setdefault("Cantina drinks", []).append(dict(name=name.strip(), template="object/tangible/food/bartender_drinks/%s.iff" % stem, price=CANTINA_PRICE))
    for shelf, items in out.items():
        seen = {}
        for it in items:
            if it["name"] in seen:
                it["name"] = "%s [%s]" % (it["name"], os.path.basename(it["template"])[:-4])
            seen[it["name"]] = True
        items.sort(key=lambda it: it["name"])
    order = [s for _, s, _ in KINDS] + ["Cantina drinks"]
    return [(s, out[s]) for s in order if s in out]

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def write(shelves):
    lines = ["-- fb_food_vendor_catalogue.lua — GENERATED by tools/foods_gen.py (Final Boss 2.16); edit the generator.",
             "-- A row with `nutrition` is a crafted food given from its template and set to a master chef's numbers (setConsumableValues);",
             "-- a row without is a cantina drink as the game makes it.",
             "FbFoodVendorCatalogue = {"]
    for shelf, items in shelves:
        lines.append("\t{ name = %s, items = {" % lua_str(shelf))
        for it in items:
            if "nutrition" in it:
                lines.append("\t\t{ name = %s, template = %s, price = %d, nutrition = %d, duration = %d, quantity = %d, filling = %d, species = %s }," % (
                    lua_str(it["name"]), lua_str(it["template"]), it["price"], it["nutrition"], it["duration"], it["quantity"], it["filling"], lua_str(it["species"])))
            else:
                lines.append("\t\t{ name = %s, template = %s, price = %d }," % (lua_str(it["name"]), lua_str(it["template"]), it["price"]))
        lines.append("\t} },")
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")

def main(argv):
    shelves = rows()
    if "--list" in argv:
        for shelf, items in shelves:
            print("%s (%d)" % (shelf, len(items)))
            for it in items:
                print("   %-40s %5d cr  %s" % (it["name"], it["price"], "n%d d%ds x%d f%d" % (it["nutrition"], it["duration"], it["quantity"], it["filling"]) if "nutrition" in it else "as is"))
        return 0
    write(shelves)
    print("wrote %s: %d shelves, %d rows" % (os.path.relpath(OUT), len(shelves), sum(len(i) for _, i in shelves)))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
